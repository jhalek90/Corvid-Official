// The title bar main gave the window (#155), as a class on the root element: titlebar-inset makes room for the
// macOS traffic lights, titlebar-frame drops the space kept for the overlay buttons. Windows gets titlebar-overlay,
// which no style uses.
const titleBarClass = `titlebar-${titleBarFromArgv(process.argv, process.platform)}`
const markTitleBar = (): void => document.documentElement?.classList.add(titleBarClass)
if (document.documentElement) markTitleBar()
else document.addEventListener('DOMContentLoaded', markTitleBar, { once: true })

export type Api = typeof api
